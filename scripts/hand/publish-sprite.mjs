// Publishes a Blender render of the grave hand into the extension: the frame
// atlas becomes assets/grave-hand.webp and its metadata src/ui/grave-sprite.ts.
//   node scripts/hand/publish-sprite.mjs <render-dir>
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const renders = resolve(process.argv[2] ?? '');
const meta = JSON.parse(await readFile(resolve(renders, 'atlas.json'), 'utf8'));
const atlas = resolve(root, 'assets/grave-hand.webp');
execFileSync('cwebp', [
  '-quiet',
  '-q',
  '84',
  '-alpha_q',
  '90',
  '-m',
  '6',
  '-sharp_yuv',
  resolve(renders, 'atlas.png'),
  '-o',
  atlas,
]);
const grip = meta.grip.map(([x, y]) => `    { x: ${x}, y: ${y} },`).join('\n');
await writeFile(
  resolve(root, 'src/ui/grave-sprite.ts'),
  `/**
 * Frame atlas for the grave hand, generated by scripts/hand/publish-sprite.mjs
 * from the Blender render in scripts/hand/grave_hand.py. Do not edit by hand.
 *
 * Frames are tiled left to right, top to bottom: the rise (fingers bunched,
 * flared, then hooked into a claw) followed by the grab (claw to fist). Points
 * are in rig units around the wrist, which the effect draws the arm from.
 */
export const GRAVE_SPRITE = {
  /** Packaged path, read by the background and handed to the page as bytes. */
  path: 'assets/grave-hand.webp',
  frame: { width: ${meta.frame.width}, height: ${meta.frame.height} },
  columns: ${meta.columns},
  rise: ${meta.rise},
  grab: ${meta.grab},
  /** The wrist, in frame pixels. */
  anchor: { x: ${meta.anchor.x}, y: ${meta.anchor.y} },
  unitsPerPx: ${meta.unitsPerPx},
  /** Centre of the closing fingers for each grab frame. */
  grip: [
${grip}
  ],
} as const;
`,
);
console.log(`atlas ${atlas}`);
